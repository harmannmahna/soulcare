def _lang(text: str) -> str:
    markers = ("hai", "nahi", "hoon", "yaar", "mann", "marna", "jeene", "ghar", "tension", "padhai")
    lower = text.lower()
    return "hinglish" if any(m in lower for m in markers) else "en"
